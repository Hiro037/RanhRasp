import re

# Гибкий поиск даты: захватывает ДД и ММ, и год (2 или 4 цифры) через точку или дефис
DATE_PATTERN = re.compile(r"\b(\d{2})[-.](\d{2})[-.](\d{2,4})\b")

# Гибкий поиск времени: ищет первые цифры часов и минут (через точку или двоеточие)
TIME_START_PATTERN = re.compile(r"\b(\d{1,2})[:.](\d{2})\b")

# Список регалий, которые нужно вырезать из ячейки преподавателя, чтобы осталось только ФИО
ACADEMIC_TITLES_PATTERN = re.compile(
    r"(?:доц|проф|к\.[а-яё\.]+\.н|ст\.преп|ассистент)\.?\s*,?\s*",
    re.IGNORECASE
)

# Шаблон для поиска чистого ФИО: Фамилия И.О. или Фамилия Имя Отчество
CLEAN_NAME_PATTERN = re.compile(
    r"\b[А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ]\s*\.\s*[А-ЯЁ]\s*\.|\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+)\b"
)